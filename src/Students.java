final class Students {
	
	private final int id;
	private final String name;
	
	public Students (int id, String name) {
		
		this.id = id;
		this.name = name;
		
	}
	
      public int getid() {
    	  return id;
    	  	  
      }
      
      public String getName() {
    	  return name;
      }
}
